export type SendStatusKind = 'sending' | 'done' | 'failed' | 'reserved' | 'cancelled' | 'unknown'

/**
 * 발송 상태값 해석 — 양수는 상태, 음수는 오류.
 * ⚠ 모르는 값은 `unknown` 으로 둔다. 임의로 「성공」이라 하지 않는다 —
 *   도착하지 않은 것을 도착했다고 말하는 쪽이 모른다고 말하는 것보다 나쁘다.
 */
export function interpretSendStatus(
  raw: string | number | null | undefined,
  channel: 'kakao' | 'sms',
): { code: number; label: string; kind: SendStatusKind } | null {
  if (raw === null || raw === undefined || raw === '') return null
  const n = Number(raw)
  if (!Number.isFinite(n)) return null
  const code = Math.trunc(n)
  const key = String(code)
  if (code < 0) {
    const msg = BAROBILL_MESSAGING_ERROR[key]
    return { code, label: msg || ('알 수 없는 오류 ' + key), kind: 'failed' }
  }
  const table = channel === 'kakao' ? KAKAO_SEND_STATUS : SMS_SEND_STATE
  const label = table[key]
  if (!label) return { code, label: '알 수 없는 상태 ' + key, kind: 'unknown' }
  const kind: SendStatusKind =
    key === '0' ? 'sending' : key === '1' ? 'done' : key === '2' ? 'failed' : key === '3' ? 'reserved' : 'cancelled'
  return { code, label, kind }
}
