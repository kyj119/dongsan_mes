// 통장 상대명(적요) 정규화.
//
// 같은 상대인데 은행이 이체 채널·경유 은행을 앞에 붙여 보내므로 표기가 갈린다.
//   성낙선 임차료 = `타행농협> 성낙선` · `타행농협&gt; 성낙선` · `홈) 농협성낙선`  (실측 3종)
// 이러면 상대명으로 묶는 반복지출 탐지에서 조용히 빠진다.
//
// ⚠️ **자동매칭(bank_match_rules)에는 쓰지 않는다.** 그쪽은 재현율보다 정밀도가 원칙이고,
//    정규화로 키를 넓히면 서로 다른 상대가 한 규칙에 걸린다. 여기 키는 **탐지·그룹핑 전용**이다.

const HTML_ENTITIES: Record<string, string> = {
  '&gt;': '>', '&lt;': '<', '&amp;': '&', '&quot;': '"', '&#39;': "'", '&nbsp;': ' ',
}

/** 은행 응답에 HTML 이스케이프가 그대로 실려오는 경우가 있다(실측 `&gt;` 18건). */
export function unescapeCounterpart(raw: string): string {
  return raw.replace(/&(gt|lt|amp|quot|#39|nbsp);/g, m => HTML_ENTITIES[m] ?? m)
}

// 이체 채널 표식 — `홈)` `홈>` `모>` `타행농협>` `타행국민>` `타행농협 ` `CMS ` 등.
//   `타행` 뒤에는 경유 은행명이 붙어 오므로 같이 흡수한다.
//   채널 토큰 뒤에 **구분자나 공백이 반드시 와야** 매치시킨다 — 그래야 `홈페이지` 같은
//   실제 상호에서 앞 글자를 떼어내지 않는다.
const CHANNEL_RE = /^(홈|모|폰|타행[가-힣]{0,4}|CMS|펌뱅킹|인터넷|스마트|자동이체)(?:\s*[)>\]]|\s)\s*/

// 채널 표식 **뒤에** 붙는 경유 은행명. 채널이 확인된 경우에만 떼어낸다 —
//   그렇지 않으면 `하나로마트` 같은 실제 상호가 `로마트` 로 잘린다.
//   실제 데이터에 나타난 은행만 넣는다. `케이`·`제일` 처럼 상호 앞머리와 겹치기 쉬운 토큰은
//   과병합 위험이 커서 제외했다(`케이엠테크` → `엠테크` 가 되는 걸 막는다).
const BANK_RE = /^(농협|국민|하나|기업|우리|신한|수협|새마을|전북|iM|KEB)\s*/

/**
 * 그룹핑용 키. 채널·경유은행 표식을 벗기고 공백을 정리한다.
 * 숫자 접미사는 **떼지 않는다** — `지로LGU+57011972` 와 `지로LGU+24081972` 는
 * 서로 다른 회선이라 합치면 안 된다. (회차번호가 매월 바뀌는 `하나생01013` 류는
 * 이 키로도 여전히 갈린다 — 알려진 한계.)
 */
export function counterpartKey(raw: string | null | undefined): string {
  if (!raw) return ''
  let s = unescapeCounterpart(String(raw)).replace(/\s+/g, ' ').trim()
  const m = s.match(CHANNEL_RE)
  if (m) {
    s = s.slice(m[0].length).trim()
    s = s.replace(BANK_RE, '').trim()
  }
  return s
}
