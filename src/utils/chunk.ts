/**
 * 변수 길이 `IN (?,?,…)` 절용 80 청크.
 *
 * D1 은 쿼리당 바인드 **~100** 이 한도라 배열이 그 수를 넘으면 「too many SQL variables」로 **500** 이 된다
 * (타입체크·빌드·스모크가 전부 통과한다 — CLAUDE.md §변수 길이 `IN (?,?,…)`). 80 인 이유는 배열 옆에
 * 상수 바인드가 몇 개 붙어도 견디기 위한 여유다(2026-09-21 `items.ts` 가 품목 100 + entity 1 = **101** 로
 * prod 500 이었다).
 *
 * ⚠️이 파일의 80 은 `scripts/bind-limit-audit.cjs` 가 **직접 읽어 검증한다** — 이 수를 올리면 감사가
 *   「청크 헬퍼가 한도를 넘는다」로 죽는다. 게이트가 이름만 믿지 않게 하려는 것이다.
 *
 * ★문장을 나눠도 **batch 는 하나로 둔다** — 원자성이 필요한 쓰기(합포장·청구확정·계산서 취소)를
 *   청크마다 따로 커밋하면 절반만 걸린 상태를 만들 수 있다.
 */
export function chunk80<T>(arr: T[]): T[][] {
  const out: T[][] = []
  for (let i = 0; i < arr.length; i += 80) out.push(arr.slice(i, i + 80))
  return out
}
