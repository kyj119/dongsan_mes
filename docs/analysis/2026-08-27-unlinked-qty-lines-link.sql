--
-- 대상 모집단 = `item_id IS NULL` 이면서 **수량이 실려 있는** 27행 1,766만.
--   뭉친 전표와 달리 수량이 있으니 연결만 하면 `avg_unit_cost` 가 **맞게** 선다 —
--   추측이 0 이라 「가장 값싼 표적」으로 골랐다.
--
-- ★그런데 실제로 안전한 건 **2행뿐**이었다. 이유를 남긴다.
-- ════════════════════════════════════════════════════════════════════════════
-- ⚠️⚠️ **미연결 라인의 수량이 「관리단위」라는 보장이 없다** — 연결의 진짜 선결조건
-- ════════════════════════════════════════════════════════════════════════════
--   스타플렉스 「SBO20 M137」 100ea @5,480 = 548,000.
--   후보 `FLEXD-137`(양면배너 후렉스 137cm)의 `avg_unit_cost` 가 **정확히 5,480** 이다.
--   그런데 그 5,480 은 **M 당 단가**다(`unit`=롤 · `base_unit`=M · `pack_size`=50 ·
--   `base_price` 279,800/롤 ≈ 5,480×50). 즉 그 매입 라인의 「100」은 **100롤이 아니라 100M**이다.
--   그대로 연결하면 새 backfill 이 `100 × packFactor(50) = 5,000M` 으로 나눠
--   **109원/M — 50배 낮은 원가**를 넣는다. 후렉스 137폭 100롤을 54.8만 원에 살 수 없다는 게 검산이다.
--   ⇒ **연결 전에 「그 수량이 롤이냐 M이냐」를 반드시 확인한다.** 품명·금액만으로 붙이면
--     08-19 base 리베이스가 고쳐 놓은 축을 라인 단위로 도로 깨뜨린다.
--
-- ⛔그래서 보류한 것들(25행) — 근거가 서면 그때 붙인다:
--   · 스타플렉스 SBO20 M137 548,000 ······ 수량 축 불명(위). 롤이면 2롤, M이면 100M
--   · 경원GH 3행 119만 ··················· `SVT-320`·`SVAT-137` 은 폭이 다르거나(130≠137)
--                                          `unit`=EA 인데 원단이라 축 자체가 의심스럽다
--   · 티피엠 잉크 2행 10.8만 ············· 「[3리터]」·「[1리터]」 규격 품목이 없다.
--                                          5L 통(49,500)에 붙이면 가중평균이 붕괴한다
--   · 엘이디포유 채널바 보강대 400mm 50만 · `SGM-TRF-R400` 은 530원인데 라인은 25,000원(47배).
--                                          `SK-2057`(25,786)·`SGM-CRF`(29,400)가 오히려 근접 — 확정 불가
--   · 우승상사 깃발 5행 460만 ············ 「청주시장 근조기」 등 **주문 제작 완제품**.
--                                          `GJG-JASU-*` 는 12,379원인데 라인은 70,000~148,000
--   · 훼미리가방 「가방」 4행 400만 ······· 품명이 「가방」뿐. `GDS-ZIP` 매입 0건이라 대조 불가
--   · 창원화학 국기지지대 360만 · 현대상사 노무단/노리본 · 정운교역 면 · 더존섬유 GHAC-2707S ·
--     삼도직물 백새이중 ··················· 대응 품목 없음(신규 등록은 계열 열거 후 용준님 확정)
--
-- ✅연결하는 2행 = **같은 공급처에 같은 품목의 매입 이력이 이미 있고 단가가 맞는** 것만.
