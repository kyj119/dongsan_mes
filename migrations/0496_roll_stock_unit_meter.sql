-- 0496_roll_stock_unit_meter.sql
-- 롤 입고 자재의 재고·소모 단위를 미터로 확정 (사용자: "전부 다 롤 단위로 입고되어서 m 단위로 소모")
--
-- ★ 단위 3층 구조 확정
--     unit       = 입고·발주 단위   → '롤'
--     base_unit  = 재고·소모 단위   → 'M'(미터)
--     pack_size  = 롤당 길이(미터)  → 입고 환산 계수(50m 롤 3개 = 재고 150m)
--
--   원단은 롤로 사 와서 미터로 잘라 쓴다. 0494·0495 에서 unit 을 '롤'로 바꿨지만
--   **차감까지 롤 수로 하던 것은 실무와 달랐다**(3m 출력에 0.06롤). 재고·소모는 미터다.
--   → 코드도 같은 회차에 수정: 차감은 `base_unit` 만 보고, `unit`(사 오는 단위)은 보지 않는다.
--
-- 대상 = `pack_size > 0` 인 자재 전부(142품목). 롤당 길이를 안다는 것이 곧 롤로 입고된다는 뜻이다.
--   ① 이미 unit='롤' 인 69품목(0494 시트 42 + 0495 코팅지 27) → base_unit 만 'M' 로
--   ② 아직 unit='yd' 인 73품목 → unit='롤' + base_unit='M'
--      조명용/비조명용 후렉스 25 · 솔벤 매쉬 9 · 부직포 5 · 양면배너 후렉스 1
--      켈 6 · 켈그레이 6 · 패트배너 6 · 합성지 5 · 합성지그레이 4 · 비점착 합성지 1
--      수성 백릿 3 · 멀티 백릿 1 · 블랙아웃 패트 1
--
-- ⚠️ 현수막 계열 85품목은 **그대로 둔다** — yd 로 입고를 체크하므로(사용자) 재고·소모가 모두
--    yd 이고 base_unit NULL 이 곧 yd 를 뜻한다. pack_size 가 없다는 것이 그 표식이다.
--
-- ⚠️ 기존 SPM011G-090 은 원래부터 base_unit='M' 이었다 — 이 마이그레이션은 그 설계를
--    전 품목으로 확장하는 것이고, 차감 코드가 'M' 을 이해하게 된 것이 이번 변화다.
--
-- ⚠️ **입고 시 롤 → 미터 환산은 아직 배선되지 않았다**(헬퍼 convertReceiptToStock 만 준비).
--    지금 재고는 0 아닌 행이 1개뿐이라 소급 문제는 없으나, 재고 실사·입고를 시작하기 전에
--    입고 경로에 환산을 붙여야 한다. 안 붙이면 롤 개수가 미터 재고에 그대로 쌓인다.
--
-- 성격: 데이터 정정(UPDATE만). 조건이 값 기준이라 멱등.

UPDATE items
   SET unit = '롤',
       base_unit = 'M',
       updated_at = CURRENT_TIMESTAMP
 WHERE is_active = 1
   AND COALESCE(deduction_method, 'ROLL') = 'ROLL'
   AND width_mm IS NOT NULL
   AND COALESCE(pack_size, 0) > 0
   AND (COALESCE(unit, '') <> '롤' OR COALESCE(base_unit, '') <> 'M');
