-- 0608: 솔벤 현수막 원단 단가 — 최근 구간 중앙값 + 인상률 환산 (12종)
--
-- 0605 는 이 원단군을 통째로 보류했다. 폭마다 마지막 매입 시점이 4월과 7월로 갈려 있어
-- 「최근 1건」을 그대로 넣으면 **시점차가 그대로 폭 역전**이 되기 때문이었다.
-- 매입처 현행 단가표가 아직 없으므로(용준님 2026-09-10) **비율로 환산해 반영**한다.
--
-- ① 최근 매입이 있는 폭 = **최근 구간(6~7월) 매입가의 중앙값**. 「최근 1건」은 못 쓴다 —
--    2026-07-31 전표에 단발 오염이 섞여 있다:
--      SVB-152 : 1,360 · 1,360 · **3,140**   → 중앙값 1,360 (최근 1건이면 3,140, 2.6배)
--      SVB-250 : 4,200 · 4,250 · 4,200 · **6,370** → 중앙값 4,225 (최근 1건이면 6,370, 1.6배)
--    `PONGE-130`(4,216,200원)과 같은 「총액이 단가 칸에 들어간 행」 패턴이다.
--
-- ② 매입이 4월에서 끊긴 폭 = 같은 기간에 **실제로 관측된 인상률**로 환산한다.
--    1~3월 → 6~7월 인상률:  90폭 ×1.138 · 127폭 ×1.115 · 152폭 ×1.106 (좁은 폭 평균 **1.12**)
--                          200폭 ×1.052 · 250폭 ×1.062 · 320폭 ×1.062 (광폭 평균 **1.06**)
--    → 150폭 이하는 ×1.12, 200폭 이상은 ×1.06. (환산분은 40·50·60·80·110폭 5종뿐이다)
--
-- 역전은 **늘지 않는다** — 전 3종({40,50,70}) → 후 3종(동일). 남는 3종은 환산 탓이 아니라
--   원 매입 기록 자체가 그렇다: 40·50폭(630)이 60폭(470)보다 비싸고 70폭(600)=80폭(600)이었다.
--   소폭 원단이 소량 생산이라 더 비싼 것일 수 있어 **임의로 손대지 않는다**.
--
-- ⚠️ SVB-180 은 단가 0 이고 매입 이력이 아예 없다 — 여기서 추정해 넣지 않는다.
--    쓰는 제품이 있으면 그 라인은 NO_PRICE 로 정직하게 빠진다.
--
-- ⚠️ 원가가 오른다 → `scripts/cost-backfill-run.cjs` 로 저장 원가 재계산 필요.
-- 되돌리기: `_bak_0608_svb` 에 원래 값이 있다.

CREATE TABLE IF NOT EXISTS _bak_0608_svb AS
SELECT id, item_code, item_name, width_mm, avg_unit_cost FROM items WHERE item_group = '솔벤 현수막';

-- ① 최근 구간 중앙값
UPDATE items SET avg_unit_cost =  690 WHERE item_code = 'SVB-070';  --   600 → 690   (6-30)
UPDATE items SET avg_unit_cost =  740 WHERE item_code = 'SVB-090';  --   650 → 740   (6-30)
UPDATE items SET avg_unit_cost = 1260 WHERE item_code = 'SVB-127';  -- 1,130 → 1,260 (6-30·7-02·7-31 동일)
UPDATE items SET avg_unit_cost = 1360 WHERE item_code = 'SVB-152';  -- 1,200 → 1,360 (6-04·6-30 ×2 · 7-31 3,140 은 오염)
UPDATE items SET avg_unit_cost = 2630 WHERE item_code = 'SVB-200';  -- 2,500 → 2,630 (5-08·6-30·7-31 동일)
UPDATE items SET avg_unit_cost = 4225 WHERE item_code = 'SVB-250';  -- 3,980 → 4,225 (4,200·4,250·4,200 중앙 · 6,370 은 오염)
UPDATE items SET avg_unit_cost = 4990 WHERE item_code = 'SVB-320';  -- 4,700 → 4,990 (6-30 ×3 · 7-31 동일)

-- ② 4월에서 끊긴 폭 — 관측 인상률 환산 (≤150폭 ×1.12)
UPDATE items SET avg_unit_cost = ROUND(avg_unit_cost * 1.12)
 WHERE item_code IN ('SVB-040', 'SVB-050', 'SVB-060', 'SVB-080', 'SVB-110');
--   40폭 630 → 706 · 50폭 630 → 706 · 60폭 470 → 526 · 80폭 600 → 672 · 110폭 810 → 907

