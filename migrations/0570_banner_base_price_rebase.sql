--     비싼 장폭(3,348)과 싼 게릴라가 빠지고 나니 실측이 내려간다 — 그대로 두면 거래처 이력이
--     없는 신규 건에 31% 높은 값을 기본 제안한다.
--
-- 기준 = **최근 3개월 가중 실효단가**(직전가 이력이 없을 때 쓰는 폴백이므로 최근이 더 예측력이 높다).
