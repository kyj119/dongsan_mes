-- AQ2-200 단가 채움 + AQ2-095 를 수성 현수막 BOM 에서 제외 (2026-09-03 용준님 확인)
-- ----------------------------------------------------------------------------
-- ★ 왜 필요한가 — 원가 판정식이 `후보 **전부** avg_unit_cost > 0` 이라(`selectRollPlacement` byPrice),
--   단가 0 인 자재가 BOM 에 하나만 섞여도 **그 제품 전체가 금액 기준 → 면적 기준으로 강등**된다.
--   AQ-BANNER(수성 현수막, 2026 매출 6.59억·6,490라인)는 20종 중 **AQ2-095·AQ2-200 둘 때문에** 그 상태였고,
--   해당 폭 구간에 걸린 147라인은 자재를 골라도 단가가 0이라 **NO_PRICE → 원가 0** 이었다.
--
-- ① AQ2-200 (2000mm) = **2,630원/yd**
--    실사에 260yd(2롤)를 보유 중인데 `avg_unit_cost` 가 0이었다. 매입이 없어서가 아니다 —
--    (주)티피엠 2026-07-31 전표에 `P150-200` 560yd × 2,630 · `S+150-200` 297yd × 2,630 이 있는데
--    **`SVB-200`(솔벤 현수막 200폭)에 연결**돼 있어 AQ2-200 쪽에는 이력이 0으로 보였다.
--    같은 거래처 광폭 단가가 수성·솔벤 사실상 동일하다는 점이 이 값을 뒷받침한다:
--      250폭 AQ2 3,900→4,200 / SVB 3,980→4,250→4,200 · 320폭 둘 다 4,640→4,990.
--    ㎡ 환산 1,438원 — 1800폭(634원/㎡)과 2500폭(1,766원/㎡) 사이로, 「2000폭부터 뛴다」와 맞는다.
--    ⚠️ 매입 이력이 없으므로 `backfill_avg_cost` 계열이 이 값을 다시 계산해 덮지 않는다.
--       200폭 매입이 앞으로도 SVB-200 으로 기록되면 이 값은 **수동 관리 대상**이다.
--
-- ② AQ2-095 (950mm) — **품목은 남기고 BOM 에서만 뺀다**.
--    제조에서는 쓰지 않는 폭이다(용준님). 매입·실사 재고도 둘 다 없다.
--    빼면 900<짧은변≤950 인 10라인(32만)이 1000폭으로 붙고, AQ-BANNER 가 금액 기준으로 복귀한다.
--    ⚠️ `items` 행은 건드리지 않는다 — 품목 자체는 있어야 한다(유통·견적 표기).

UPDATE items
   SET avg_unit_cost = 2630,
       updated_at    = CURRENT_TIMESTAMP
 WHERE item_code = 'AQ2-200';

DELETE FROM product_materials
 WHERE product_item_id = (SELECT id FROM items WHERE item_code = 'AQ-BANNER')
   AND material_item_id = (SELECT id FROM items WHERE item_code = 'AQ2-095');

-- ③ SPM022G-152 (그레이시트 1520폭) = **3,100.6원/m**
--    단가 0 자재 전수(52종) 중 **매입 근거가 있는 유일한 품목**이다.
--    (주)서울경금속 `LG-DPM1520mmSPM022G` 1롤 × 155,030원 3건(2026-07-01·07-06·07-13).
--    base_unit='M' · pack_size=50 → **롤 단가 ÷ 50 = 3,100.6원/m**.
--    ⚠️ 축 검증 = 형제의 ㎡ 단가와 대조했다(50배 사고를 막는 유일한 방법):
--       105폭 1,986 · 127폭 1,927 · 137폭 1,962 · **152폭 2,040원/㎡** → 계열과 일치(+3%).
--       ÷50 을 빠뜨렸다면 102,000원/㎡ 로 형제의 51배가 됐을 것이다.
--    영향 = `SV-SHEETG`(1,076만) · `UV-SHEETG`(199만) 이 금액 기준으로 복귀한다.
--
-- ⛔ 나머지 46종은 채우지 않는다 — **매입 이력이 0건**이라 근거가 DB 에 없다.
--    미연결(item_id NULL) 라인까지 훑어도 0건이었다. 추정으로 채우면 원단 50배 사고와 같은 축이다.
--    영향 제품(BOM 전 자재가 0 → 원가 0): UV-PDK-F 320만 · UV-SPC031G 180만 · UV-PDK-J 166만 ·
--    UV-PRM-W 95만 · AQ-BKLT 45만 · UV-BKLT · SV-PATB · UV-PRM-Y (2026 합 7,212만).
--    ※ 종전에도 0이었다 — 이번 변경으로 나빠지는 것은 없다. 실제 매입가 확보 후 별도 처리.

