-- 0564: 엡손 솔벤잉크 그룹명에서 「11색기」를 빼고 **장비 모델**로 통일
--
-- 배경 = 실사표가 `item_group` 을 그룹 헤더로 쓰기 시작하면서(2026-09-04) 화면에
--   「엡손솔벤잉크 11색기」가 뜬다. 용준님 요청 = **11색기 빼 달라**.
--
-- ★그냥 지우면 「엡손솔벤잉크」가 되어 **형제 그룹과 구분이 사라진다** —
--   `엡손솔벤잉크 80610`(11품목)이 따로 있고, 그건 **다른 장비**의 잉크다.
--   구분 축은 색 수가 아니라 **장비 모델**이고, 품목명이 이미 그 축을 쓰고 있다
--   (`엡손 솔벤잉크 9140/8140 C`). 그래서 그룹도 모델로 맞춘다:
--     엡손솔벤잉크 11색기  →  엡손솔벤잉크 9140/8140
--   이러면 80610 그룹과 이름 규칙이 같아진다.
--
-- ⚠️ 「N색기」가 붙은 그룹이 셋 더 있다 — `전사잉크 KM테크 8색기`(8) · `엡손솔벤잉크 6색기`(6) ·
--    `전사잉크 KM테크 4색기`(4). **손대지 않는다** —
--    KM테크는 같은 브랜드에서 **색 수가 곧 장비 구분**이라 색 수가 정보이고,
--    엡손 6색기는 재고 0·원가 0 인 죽은 품목이라 이름을 고쳐도 화면에 안 뜬다.
--    요청받은 것만 고친다.
--
-- ⚠️ 되돌리기 = UPDATE items SET item_group = '엡손솔벤잉크 11색기'
--               WHERE item_group = '엡손솔벤잉크 9140/8140';

UPDATE items
   SET item_group = '엡손솔벤잉크 9140/8140', updated_at = datetime('now')
 WHERE item_group = '엡손솔벤잉크 11색기';
