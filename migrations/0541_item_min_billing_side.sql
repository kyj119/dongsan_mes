-- 0541: 품목별 최소 청구 변(cm) — AREA 금액 산식의 「최소 1m」를 품목별로 끌 수 있게 한다.
--
-- 왜: 「10cm 올림 + 최소 1m」는 현수막·시트 계열의 규칙이고 전 품목 공통이 아니었다.
--   검증(2026-08-25) — 운영 중 AREA 53종의 base_price 를 이 규칙으로 53/53 재현(실면적 기준은 9/53).
--   그러나 **UV 판재는 실규격 그대로 청구**한다(용준님 확인). 자작나무 6T 는 62건 중 55건(89%)이
--   1㎡ 미만이라 최소 1m 를 적용하면 ㎡단가가 8,000→33,300→109,500 으로 13배 벌어지지만,
--   실면적 기준이면 ≈120,000 으로 평평하다. 포맥스 5T 도 30×15=2,500·40×30=7,000 → 55,556·58,333원/㎡.
--   ⇒ 단가를 채우기 전에 이 예외가 없으면 소품이 최대 11배 과청구된다(0.09㎡ 조각이 1㎡ 로 계산).
--
-- ★기본값 100 = 종전 동작. 이 마이그레이션만으로는 **아무 금액도 바뀌지 않는다**.
--   예외를 켤 품목은 별도 판단(품목별 실거래 분포 근거 → 사람이 확정).
--   0 = 최소청구 없음(실규격). 코드에서 0 은 유효값이라 `|| 100` 폴백 금지(orderLineAmount.resolveMinSide).
--
