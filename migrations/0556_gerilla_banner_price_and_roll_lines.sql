-- 0556: 게릴라 현수막 — 장당 기준단가 등록 + 원단(yd) 판매 7줄을 자재로 이관
--
-- 배경 = 2026-09-03. `AQ-SYNG`(수성 합성지 그레이)와 **똑같은 병**이다. 제품 코드에 원단 롤
--   판매가 붙어 있어서, 실적에서 무엇을 재도 원단 단가가 나온다(제가 실제로 460원/장을
--   완제품 단가로 뽑았고, 용준님이 쓰시는 값은 4,500원이었다 — 10배 어긋났다).
--
-- 판정 근거:
--   ① 7줄의 `content` 가 **`166yd*1`·`166yd*2`·`166yd*3`** — yd 단위 롤이다.
--   ② `specification` 이 **`90폭`**, 규격은 `0x0`(가로세로 없음).
--   ③ 단가 410~480원 = yd 단가. 완제품 장당가(4,500원)와 자릿수가 다르다.
--   ④ `AQD-090 수성 현수막원단 저밀도 90cm 400원/yd`(47줄)의 라인과 **모양이 완전히 같다** —
--      2026-06-26 AQD-090 `90x0 q=166 @460 = 76,360 내용=166yd*1`
--      2026-07-01 AQ-GERILLA `90x0 q=166 @460 = 76,360 내용=166yd*1`
--   ⑤ 거래처가 애드스타·햇살광고·프린트팩토리 = 동종업체(원단 도매).
--   원단이 게릴라 현수막용이라 이름을 헷갈린 것으로 보인다.

-- ── 1. 완제품 기준단가 + 과금축 ──────────────────────────────────────────────
-- 용준님 확인값 = 기본 **4,500원/장**(기존 최소 3,800 · 수량에 따라 4,500·5,000·6,000).
-- 장당 고정가이므로 과금축은 `AREA` 가 아니라 **`FIXED`** 다 — AREA 로 두면 규격을 넣는 순간
-- 면적이 곱해져 4,500원이 통째로 어긋난다.
-- ⚠️ 수량 구간 단가(166장 4,500 / 500장 3,800)는 **시스템에 담을 곳이 없다** — `price_lists` 는
--    거래처별 `adjustment_percent` 한 축뿐이다. 구간 단가표를 새로 만드는 대신 **사람이 라인
--    에누리로 조정**하기로 했다(2026-09-03 용준님 판단). 그 경로는 이미 있다 —
--    `orders/create.ts`·`update.ts` 가 자동값과의 차액을 `line_discount`+`discount_reason` 으로
--    기록한다. ⚠️다만 prod 사용 이력이 **0줄**이라 실사용은 아직 확인된 바 없다.
UPDATE items
   SET base_price = 4500,
       pricing_method = 'FIXED',
       updated_at = datetime('now')
 WHERE item_code = 'AQ-GERILLA';

-- ── 2. 원단 판매 7줄을 AQD-090 으로 이관 ─────────────────────────────────────
-- `item_name` 은 손대지 않는다 — 사람이 그때 적은 글자가 남아 있어야 경위를 읽을 수 있다.
-- ⚠️ 되돌리기 = 아래 id 로 되돌린다. AQD-090 에는 원래 47줄이 있어 폭·내용으로는 구분이 안 된다.
--    옮기는 라인 id(실행 전 조회분, 2026-09-03):
--      22600, 22717, 22847, 22898, 22988, 23127, 23273
--    복구 = UPDATE order_items SET item_id=(SELECT id FROM items WHERE item_code='AQ-GERILLA')
--           WHERE id IN (22600,22717,22847,22898,22988,23127,23273);
UPDATE order_items
   SET item_id = (SELECT id FROM items WHERE item_code = 'AQD-090'),
       updated_at = datetime('now')
 WHERE id IN (22600, 22717, 22847, 22898, 22988, 23127, 23273)
   AND item_id = (SELECT id FROM items WHERE item_code = 'AQ-GERILLA');

