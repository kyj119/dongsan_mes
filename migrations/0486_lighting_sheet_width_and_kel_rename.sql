-- 0486_lighting_sheet_width_and_kel_rename.sql
-- ① 조명시트 width_mm 채우기 ② LGSHT-122 를 켈시트로 재분류 (사용자 확인)
--
-- ─────────────────────────────────────────────────────────────────────────────
-- ① 조명시트 width_mm 채우기
--
--   폭이 규격 문구("122폭"·"137폭")에만 있고 width_mm 이 NULL 이라, 자재 폭매칭
--   (autoDeductInventory·autoDeductPostProcessingMaterials)이 `width_mm IS NOT NULL`
--   조건에서 **후보로조차 잡지 못했다** = 조명시트는 자동차감 대상 밖이었다.
--   제품번호는 늘어도 폭은 122/137 두 가지뿐이라 개별 품목 구조를 유지한 채 값만 채운다.
--
--     LT4071M · LT4080M · LT4510 · LC6770P → 1220
--     LM5400-137 · LW2800M                 → 1370   (SPT031M 은 이미 1370)
--
--   ⚠️ JMS-GEN(범용)은 NULL 유지 — 규격이 '색상·폭=매입 메모'라 폭이 확정되지 않는다.
--      임의로 채우면 실제와 다른 폭으로 매칭돼 잘못된 자재를 차감한다.
--
--   ⚠️ 부작용(의도된 것): 폭을 채우면 그룹 내 동폭 경합이 새로 2조합 생긴다.
--        1220mm : LC6770P · LT4071M · LT4080M · LT4510   (4개)
--        1370mm : LM5400-137 · LW2800M · SPT031M         (3개)
--      이건 분류 오류도 제조사 대체재도 아니고 **색상·타입이 다른 별개 제품**이 한 그룹에
--      정상적으로 모여 있는 것이다. 자동차감이 무엇을 집을지는 group_sort 미지정 상태에서
--      id 순으로 결정론적이긴 하나 **업무적으로 옳은 선택은 아니다**.
--      → 우선 소비 자재는 품목 페이지 > 그룹 일괄수정 > '우선 소비 자재'에서 지정할 것.
--         (실사용 빈도는 LT4080M 7건 · LT4071M 6건 · 나머지 1~2건)
--      현재 product_materials 연결은 SPT031M 1건뿐이라 당장의 오차감 위험은 없다.
--
-- ─────────────────────────────────────────────────────────────────────────────
-- ② LGSHT-122 → 켈시트 재분류 (사용자 확인)
--
--   '조명용시트'는 **LT4000번대**를 부르는 통상 명칭이고, **LA9000번대는 켈시트**로 부른다.
--   LGSHT-122 의 실제 제품은 매입 기재상 LA9423NH → 조명용시트가 아니라 켈시트다.
--   이름과 그룹을 제품 실체에 맞춘다.
--
--   ⚠️ item_code 'LGSHT-122'는 그대로 둔다 — 참조는 전부 items.id 기준이라 코드 변경
--      이득이 없고, 발주 이력의 기재명과 대조할 때 오히려 추적이 쉬워진다.
--   ⚠️ 기존 '켈 30M 호홍'(KEL-*)과는 합치지 않았다 — 그쪽은 호홍 제조 30M 롤이고
--      폭 구성도 600/900/1270/1520 로 1220 이 없다. 동일 자재라는 근거가 없다.
--
-- 성격: 데이터 정정(UPDATE만). item_code 기준이라 멱등.

-- ① 조명시트 폭
UPDATE items SET width_mm = 1220, updated_at = CURRENT_TIMESTAMP
 WHERE item_code IN ('LT4071M', 'LT4080M', 'LT4510', 'LC6770P');

UPDATE items SET width_mm = 1370, updated_at = CURRENT_TIMESTAMP
 WHERE item_code IN ('LM5400-137', 'LW2800M');

-- ② 켈시트 재분류
UPDATE items
   SET item_name  = '켈시트 LA9423NH',
       item_group = '켈시트 LA9423NH',
       updated_at = CURRENT_TIMESTAMP
 WHERE item_code = 'LGSHT-122';
