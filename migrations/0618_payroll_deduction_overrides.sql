-- 0618: 급여 공제 수동 오버라이드 (T2 엑셀 입력)
--
-- 왜: 4대보험 공제액은 `calcDeductions` 결과만 저장되고 **수동 입력 경로가 없었다**
--   (`other_deduction` 만 예외). 그래서 공단 고지·이카운트 대장과 값이 다를 때
--   맞출 방법이 아예 없었다. 2026-09-17 대조에서 보수월액 축 차이 −143,580원이
--   구조적으로 남는 것이 확인됐다 — 공단 보수월액은 전년도 기준 1년 고정인데
--   MES 는 당월 과세급여를 쓰기 때문이고, 4월 건강보험 정산·감면은 공단만 아는 값이다.
--
-- 왜 JSON 한 칸인가:
--   ① 기존 컬럼(national_pension 등)에는 **최종값**이 그대로 들어간다 → 급여대장 집계·CSV·
--      명세서가 전부 기존 경로를 쓰고, 조회 쿼리를 하나도 안 고쳐도 된다.
--   ② 이 칸은 "무엇을 사람이 고정했는가"의 기록이다. 재계산(근태 불러오기)이 돌 때
--      calcDeductions 결과를 이 값으로 **다시 덮어써야** 오버라이드가 살아남는다.
--      컬럼을 6개 만들면 6개 전부를 모든 계산 경로에서 다뤄야 하는데, 실제로 쓰는 것은
--      "덮어쓸 항목 집합"이라 형태가 맵에 가깝다.
--   ③ 집계는 기존 컬럼으로 하므로 JSON 을 SQL 로 뒤질 일이 없다(있으면 설계가 틀린 것).
--
-- 키: np(국민연금) hi(건강) ltc(장기요양) ei(고용) it(소득세) lt(지방소득세)
--   예: {"np":302570,"hi":288190} — 없는 키는 계산값을 그대로 쓴다.
--   값은 정수(원). 0 도 유효한 오버라이드다(= 공제 안 함). "해제"는 키를 빼는 것.

ALTER TABLE payroll ADD COLUMN deduction_overrides TEXT;

-- 누가 언제 고정했는지 — 오버라이드는 계산을 이기므로 추적이 없으면 원인 규명이 불가능하다.
ALTER TABLE payroll ADD COLUMN deduction_overrides_at DATETIME;
ALTER TABLE payroll ADD COLUMN deduction_overrides_by INTEGER;
