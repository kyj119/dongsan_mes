-- 0590: 「미등록 차입금 2건」은 미등록이 아니었다 — 계좌번호만 안 붙어 있었다
--
-- `audit:loan-bank`(0589 와 함께 신설)가 「이자를 내고 있는데 loans 에 없는 대출계좌 2개」를
-- 지목했다: `60298019970342` 9건 12,354,697 · `60298020242942` 8건 175,385 (둘 다 법인2).
-- 새로 등록하려고 원금을 역산하다 보니 **이미 등록된 #21·#22 였다.**
--
-- 근거는 추정이 아니라 그 행들의 `notes` 원문이다:
--   #21 notes: "…2026-03-13 원금 10,015,928 일시상환 실측" ← `60298019970342` 의 2026-03-13 출금과 동일
--   #22 notes: "…형제 계좌 60298019970342 의 원금상환 전후 이자 변동 역산값을 준용했다"
--              ← 계좌번호를 **글로는 알고 있었는데 넣을 칸이 없었다**(account_no 는 0589 에서 생겼다)
--
-- 교차 검산도 맞는다:
--   #21 등록 월납 285,000 vs 실측 월이자 283,588 (차 0.5%) · 역산 잔액 89,436,426 vs 등록 90,000,000 (차 0.6%)
--   #22 등록 월납  22,000 vs 실측 월이자  21,923 (차 0.4%)
-- 법인2에 계좌번호가 빈 차입금은 이 둘뿐이라 다른 후보도 없다.
--
-- ★교훈: 「없다」고 판단하기 전에 **같은 표의 자유텍스트를 먼저 읽는다.** 값이 없는 게 아니라
--   담을 칸이 없었을 뿐인 경우가 있다.
--
-- 멱등: account_no IS NULL 인 행만 채운다.

UPDATE loans SET account_no = '60298019970342' WHERE id = 21 AND account_no IS NULL;
