-- 0548_designer_intake_qty_unit.sql
-- 대기물 수량 단위 표기(「조」) — 검산용 흔적.
--
-- 왜: 가로등배너는 **파일 한 장(120×180)이 낱개 두 장(60×180)** 이 된다. 현장은 「1조」로 세지만
--     품목은 `전사 가로등배너 폰지 60×180 · unit=EA` 이고 청구는 이카운트와 같이 **개**로 한다.
--     환산(×2)은 패널 gatherParams **한 곳**에서 끝내므로 `qty` 는 언제나 개다.
--     그런데 환산이 일어났다는 사실이 아무 데도 안 남으면 나중에 "2개가 맞나 1개가 맞나"를 못 가린다.
--     → 단위만 남긴다. 'set' = 조로 입력됨(값은 이미 개). NULL = 개로 입력됨(기존 동작).
--
-- ⚠️ 수량 축을 새로 만들지 않는다 — 품목·단위·청구는 전부 개 그대로다. 이 컬럼은 **표시·검산 전용**이고
--    어떤 계산에도 쓰이지 않는다(쓰기 시작하면 청구 축이 둘로 갈린다).
--
-- 성격: additive(컬럼 1). ALTER는 멱등 아님 — 신규 1회 적용(feedback-migration-idempotency).
-- 적용: 로컬/원격 모두 `wrangler d1 execute … --file` 직접 실행(d1_migrations 트래킹 불일치).

ALTER TABLE designer_intakes ADD COLUMN qty_unit TEXT;
