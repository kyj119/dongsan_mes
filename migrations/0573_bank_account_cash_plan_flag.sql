-- 자금계획 시작잔액에 넣을 계좌 지정 (2026-09-05)
--
-- 왜: 자금계획 예측의 시작잔액이 '활성 법인계좌 전부'였다. 마이너스통장은 잔액이 음수(= 빌려 쓴 돈)라
--     합산하면 prod 기준 -4.2억에서 출발했고, 그래서 90일 예측의 위험일이 **91일 중 91일**로
--     항상 빨간불이었다 — 경고가 상시 켜져 있으면 신호 구실을 못 한다.
--
-- 무엇: 계좌마다 '이 잔액을 계획의 출발점에 넣을지'를 둔다. is_overdraft(마통이냐 = 사실 판정)와
--       분리한 이유는, 보증금 예치처럼 잔액은 있지만 자금 운용에 못 쓰는 예금 계좌도 뺄 수 있어야 해서다.
--       끄더라도 거래내역·입금매칭·실적 탭 집계는 그대로다. 계획의 시작 숫자에서만 빠진다.
--
-- 기본값: 예금은 포함(1), 마이너스통장은 제외(0)로 깔아 둔다 → 손대지 않아도 의도한 동작이 된다.
ALTER TABLE bank_accounts ADD COLUMN include_in_cash_plan INTEGER NOT NULL DEFAULT 1;

UPDATE bank_accounts SET include_in_cash_plan = 0 WHERE is_overdraft = 1;
