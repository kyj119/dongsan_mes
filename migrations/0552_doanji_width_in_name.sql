-- 0552: 도안지 제품 2종의 이름에 폭을 넣는다 (0550 이 만든 이름 충돌 해소)
--
-- 0550 에서 도안지 125폭(1685)을 제품으로 신설하면서 이름을 100폭(1558)과 똑같이 「도안지」로
-- 뒀다. 그래서 0551 로 솔벤 텐트천 충돌을 없애자마자 **같은 결함이 도안지로 옮겨왔다**
-- (PRODUCT 동명 그룹 1건).
--
-- 왜 문제인가: 패널의 `itemIdOf`/`productIdOf` 는 **이름 정확일치의 첫 매치**를 잡는다.
--   이름이 같으면 폭을 골라도 항상 앞의 것(1558)으로 해소되고, 주문서는 그 `item_id` 로 단가를
--   끌어온다 — 사람은 125폭을 골랐는데 조용히 100폭 단가가 실린다.
--
-- 왜 「제품 1개 + 자재 폭별」(수성 텐트천 모델)로 안 가나: 도안지는 폭 자체가 **파는 단위**다
--   (용준님 확인 — 간판 나가면서 플로터로 도안을 그려 함께 출고). 태극기 7호·8호처럼 폭이
--   품목 이름의 일부여야 사람이 고를 수 있다. `specification` 은 그대로 둔다(중복 표기가 아니라
--   화면에서 규격 열로 쓰인다).
--
-- 자재 843(도안지 125폭·yd)은 그대로 「도안지」다 — 매입 축이라 제품과 이름이 갈려도 무방하고,
-- product_materials 매핑은 id 기반이라 이름을 바꿔도 끊기지 않는다.

UPDATE items SET item_name = '도안지 100폭', updated_at = datetime('now')
 WHERE item_code = 'RM-DOAN-100' AND item_name = '도안지';

UPDATE items SET item_name = '도안지 125폭', updated_at = datetime('now')
 WHERE item_code = 'RM-DOAN-125' AND item_name = '도안지';
