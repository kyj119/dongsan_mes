-- 0580: 꺼져 있던 표준 판관비 계정 되살리기 (광고선전비 · 도서인쇄비 · 수선비)
--
-- ■ 무엇이 문제였나
--   표준 판관비 계정 셋이 `is_active=0` 이라 화면에서 **고를 수 없었다**. 그런데 데이터는 들어 있다 —
--   광고선전비(법인1) 2건 4,152,000 · 도서인쇄비(법인2) 6건 137,170. 고를 수 없는 계정에 돈이
--   갇혀 있고, 새로 생기는 같은 성격의 지출은 갈 데가 없어 `잡비`로 샌다.
--
--   ★`수선비` 는 **결번이 아니라 비활성**이었다. 법인1 #11 · 법인3 #47 이 꺼져 있어서 활성만 보는
--     감사에는 「법인2 에만 있음」으로 보였다. **is_active 를 안 보면 결번과 비활성을 혼동한다.**
--
-- ■ 왜 되살리나 (지우지 않고)
--   셋 다 국세청 표준계정과목이다. 계정을 줄이는 게 아니라 **표준 한 벌을 갖추는 것**이 목적이고,
--   선택지가 없으면 분류가 `잡비` 로 뭉쳐 손익 해상도가 떨어진다.
--
-- 법인99(E2E 테스트)는 건드리지 않는다 — 실 운영 축이 아니다.
--
-- 멱등: is_active=1 로 세우는 것이라 재실행 무해.

UPDATE expense_categories SET is_active = 1
WHERE name IN ('광고선전비', '도서인쇄비', '수선비')
  AND entity_id IN (1, 2, 3)
  AND is_active = 0;
