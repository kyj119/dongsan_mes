-- 0577: UV 폼보드 2라인의 규격이 **mm 로 입력**돼 원가가 100배 부풀었다
--
-- 무엇이 잘못됐나 (2026-09-07 발견 · 용준님 확인):
--   `order_items.width/height` 는 **cm** 축인데 두 라인이 mm 값으로 들어왔다.
--     · id 26884  E1-20260820-I025 「선양오크맥주」  120×240 (실제 12×24cm) ×1,320장
--     · id 5809   E1-20260205-I025 「농촌일손」      600×400 (실제 60×40cm) ×1장
--   품목이 AREA 라 면적이 그만큼 커졌고, 입력자가 **단가를 낮춰 금액을 맞췄다** —
--   그래서 청구액은 맞는데 규격·단가만 어긋난 채 남았다. 원가는 규격을 보므로 통째로 틀렸다:
--   26884 한 라인이 매출 264만에 원가 **1,660만**(폼보드 판재 1,277장 + UV잉크 3,802㎡).
--   품목 전체가 「단가 점검 필요」로 수익성 집계에서 빠졌다(원가율 201%).
--
-- ★최소청구 1m 규칙이 배율을 정한다 — 실면적비는 100배지만 12×24cm 는 **1㎡로 올림 청구**되므로
--   실제 배율은 2.88㎡ ÷ 1㎡ = **2.88배**다. 단가도 정확히 2.88배 낮게 들어가 있었다(2,000 → 694).
--   ⇒ 새 단가 = **장당 금액**(= amount ÷ 수량). 1㎡ 최소청구라 ㎡단가와 장당가가 같아진다.
--
-- ★`amount` 는 건드리지 않는다 — 청구액은 원래 맞다. 이건 청구 정정이 아니라 **규격·단가 표기 정정**이다.
--   `auto_amount`·`line_discount` 는 새 규격·단가로 자동값이 정확히 재현되므로 함께 맞춘다
--   (실측: 12×24cm ×1,320 @2,000 → 2,640,000 = 실제 금액 · 60×40cm ×1 @21,300 → 21,300 = 실제 금액).
--
-- ★단가 21,300원/㎡ 은 **형제 라인이 증명한다** — 같은 품목의 60×40cm ×9장 라인이 @21,300 이다.
--
-- ⚠️ 과금축은 바꾸지 않는다. 이 품목 15개 표본이 **15/15 전부 AREA 규칙(10cm 올림 + 최소 1m)으로
--    재현**된다 — 작은 조각이 「장당」처럼 보이는 것은 1㎡ 최소청구의 결과이지 축 혼재가 아니다.
--
-- 되돌리기: `_bak_0577_uv_foam_line_size` 에 원값이 있다.

CREATE TABLE IF NOT EXISTS _bak_0577_uv_foam_line_size AS
  SELECT id, width, height, unit_price, amount, auto_amount, line_discount
    FROM order_items WHERE id IN (26884, 5809);

-- 선양오크맥주 — 120×240mm ×1,320장, 장당 2,000원
UPDATE order_items
   SET width = 12, height = 24, unit_price = 2000,
       auto_amount = 2640000, line_discount = 0
 WHERE id = 26884 AND width = 120 AND height = 240 AND amount = 2640000;

-- 농촌일손 — 600×400mm ×1장, 장당 21,300원
UPDATE order_items
   SET width = 60, height = 40, unit_price = 21300,
       auto_amount = 21300, line_discount = 0
 WHERE id = 5809 AND width = 600 AND height = 400 AND amount = 21300;
