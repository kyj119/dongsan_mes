-- 0549_birch6t_real_area_billing.sql
-- UV 자작나무 6t 만 실면적 청구로 — `min_billing_side_cm = 0`.
--
-- 왜 이 품목만인가 (2026-09-01 실측, 근거 = order_items.amount + 실규격. unit_price 는 쓰지 않았다 —
--   이관 unit_price 는 amount 에서 역산된 값이라 어느 산식에 넣어도 되돌아온다. 순환이라 증거가 못 된다):
--
--   UV 자작나무 6t (62건) — 장당금액 ÷ 실면적
--     120×30   40,000 → 111,111/㎡      65×65  47,000 → 111,242/㎡
--     122×300 510,000 → 139,344/㎡      52×10   6,000 → 115,384/㎡
--     120×110 145,000 → 109,848/㎡      50×10   6,000 → 120,000/㎡
--   → 1㎡ 미만 조각까지 **면적당 단가가 평평하다**(P25~P75 = 111,111~182,930, 산포 1.65배).
--     최소청구(각 변 100cm)를 적용하면 같은 표본이 6,250~42,875 로 **6.86배** 벌어진다.
--     2026-08-25 검토가 독립적으로 ≈120,000/㎡ 를 냈고 이번 중앙값 122,983 과 일치한다.
--
-- ⛔ 다른 판재는 **건드리지 않는다**. 「UV 판재는 실면적」이 하나의 정책이 아님이 이번에 드러났다:
--     · UV 자작나무 12t — 30×17·30×14·30×12·300×17 이 **전부 21,000원**(크기 무관) = 개당 고정에 가깝다
--     · UV 포맥스 5T   — 40×40 125,000/㎡ vs 80×60 15,000/㎡ (8배 널뜀)
--     · UV 포맥스 8T   — 39×20 294,871/㎡ vs 157×95 23,466/㎡ (12배 널뜀) · 표본 20건 중 9건이 같은 규격
--   최소청구를 꺼도 자동값이 맞지 않는다(면적당 단가 자체가 손 견적이다). 뭉뚱그려 0 을 걸면 더 틀린다.
--   → 실사용이 시작되면 `order_items.line_discount`(0501) 에 사람이 덮은 방향이 쌓인다. 그게 정답지다.
--
-- 되돌리기: UPDATE items SET min_billing_side_cm = 100 WHERE item_code = 'UV-JJN-06T';
-- 소급 없음 — 이미 저장된 주문의 금액은 건드리지 않는다(스냅샷 보존). 앞으로 계산되는 라인만 바뀐다.
--
-- 성격: 데이터 1행 UPDATE. 멱등(같은 값 재적용 무해).
-- 적용: 로컬/원격 모두 `wrangler d1 execute … --file` 직접 실행.

UPDATE items SET min_billing_side_cm = 0 WHERE item_code = 'UV-JJN-06T';
