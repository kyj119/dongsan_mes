-- 0624: 조기출근을 연장수당으로 인정하지 않는 직원 표시
--
-- 배경: 2026-07-12 정책으로 「조기출근(출근 전)도 연장수당으로 지급」이 전 직원 공통이다
--   (payroll/core.ts 집계: overtime_hours + early_hours). 그런데 사람마다 합의가 다르다 —
--   이득용 부장은 아침에 일찍 나오지만 **초과근무로 인정하지 않기로** 합의돼 있다(2026-09-18 확인).
--   그 결과 MES 만 452,110원을 더 얹어 이카운트와 어긋났다(8월 MES 4,452,310 ↔ EC 4,000,200).
--
-- 왜 컬럼인가: 근태 데이터(early_hours)는 **사실 그대로** 남겨야 한다. 조기출근을 0 으로
--   지우면 「언제 나왔나」가 사라지고 되돌릴 수도 없다. 지급에 반영할지는 **사람 축의 합의**이므로
--   직원 속성으로 둔다(§4대보험 가입자격과 같은 형태 — 사실은 그대로, 적용 여부만 사람이 정한다).
--
-- 0 = 조기출근을 연장수당에 포함(기존 동작·기본값) · 1 = 제외.

ALTER TABLE employees ADD COLUMN exclude_early_from_overtime INTEGER NOT NULL DEFAULT 0;
